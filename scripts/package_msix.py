NS = {
    'f': 'http://schemas.microsoft.com/appx/manifest/foundation/windows10',
    'uap': 'http://schemas.microsoft.com/appx/manifest/uap/windows10',
    'uap3': 'http://schemas.microsoft.com/appx/manifest/uap/windows10/3',
    'uap5': 'http://schemas.microsoft.com/appx/manifest/uap/windows10/5',
    'uap10': 'http://schemas.microsoft.com/appx/manifest/uap/windows10/10',
    'rescap': 'http://schemas.microsoft.com/appx/manifest/foundation/windows10/restrictedcapabilities',
    'virtualization': 'http://schemas.microsoft.com/appx/manifest/virtualization/windows10',
}
DEVELOPMENT_IDENTITY = {
    'name': 'PeerBrush.LocalTest',
    'publisher': 'CN=PeerBrush Local Test',
    'publisher_display_name': 'PeerBrush local test only',
}
ASSETS = {'Square44x44Logo.png': 44, 'Square150x150Logo.png': 150, 'StoreLogo.png': 50}
PROJECT_TYPES = ['.psd', '.psb']
# Only add these with the maintainer's explicit choice; never change UserChoice.
OPTIONAL_TYPES = {'.png', '.jpg', '.jpeg', '.webp', '.bmp', '.gif', '.tif', '.tiff', '.svg'}


def sha(data):
    return hashlib.sha256(data).hexdigest()


def identity_values(identity, development=False):
    if not isinstance(identity, dict) or set(identity) != set(DEVELOPMENT_IDENTITY):
        raise ValueError('Identity must contain name, publisher and publisher_display_name')
    if any(not isinstance(v, str) or not v.strip() or any(ord(c) < 32 for c in v) for v in identity.values()):
        raise ValueError('Identity fields must be nonempty text without control characters')
    if any('REPLACE_' in v or '{{' in v for v in identity.values()):
        raise ValueError('Partner Center identity placeholders must be replaced')
    name = identity['name'].casefold()
    reserved = {'con', 'prn', 'aux', 'nul', *(f'com{i}' for i in range(1, 10)), *(f'lpt{i}' for i in range(1, 10))}
    if (not re.fullmatch(r'[A-Za-z0-9.-]{3,50}', identity['name']) or name.endswith('.')
            or name.split('.')[0] in reserved or name.startswith('xn--') or '.xn--' in name):
        raise ValueError('Invalid package identity Name')
    if not identity['publisher'].startswith('CN=') or len(identity['publisher']) > 8192:
        raise ValueError('Publisher must be the exact certificate/Partner Center distinguished name')
    if len(identity['publisher_display_name']) > 256:
        raise ValueError('Publisher display name is too long')
    if 'OID.2.25.311729368913984317654407730594956997722' in identity['publisher']:
        raise ValueError('Special unsigned-install identities are not generated by this build script')
    if not development and (identity['name'] == DEVELOPMENT_IDENTITY['name'] or identity['publisher'] == DEVELOPMENT_IDENTITY['publisher']):
        raise ValueError('Local test identity requires --development-identity; it is not a Store identity')
    return identity


def derived_package_family(identity):
    """Portable identity cross-check; Windows API remains authoritative at build."""
    digest = hashlib.sha256(identity['publisher'].encode('utf-16le')).digest()[:8]
    rfc = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567'
    crockford = '0123456789abcdefghjkmnpqrstvwxyz'
    publisher_id = base64.b32encode(digest).decode().rstrip('=').translate(str.maketrans(rfc, crockford))
    return identity['name'] + '_' + publisher_id


def native_package_family(identity):
    """Use Microsoft's supported API without installing/registering a package."""
    if os.name != 'nt':
        raise ValueError('Native package-family validation requires Windows')
    import ctypes
    from ctypes import wintypes
    class PackageId(ctypes.Structure):
        _fields_ = [('reserved', wintypes.UINT), ('processorArchitecture', wintypes.UINT),
                    ('version', ctypes.c_uint64), ('name', wintypes.LPWSTR),
                    ('publisher', wintypes.LPWSTR), ('resourceId', wintypes.LPWSTR),
                    ('publisherId', wintypes.LPWSTR)]
    function = ctypes.WinDLL('kernel32').PackageFamilyNameFromId
    function.argtypes = [ctypes.POINTER(PackageId), ctypes.POINTER(wintypes.UINT), wintypes.LPWSTR]
    function.restype = wintypes.LONG
    package_id = PackageId(0, 9, 0, identity['name'], identity['publisher'], None, None)
    length = wintypes.UINT(0)
    if function(ctypes.byref(package_id), ctypes.byref(length), None) != 122 or not 2 <= length.value <= 65:
        raise ValueError('Windows rejected the configured package identity')
    result = ctypes.create_unicode_buffer(length.value)
    if function(ctypes.byref(package_id), ctypes.byref(length), result) != 0:
        raise ValueError('Windows could not derive the configured package family')
    return result.value


def validate_package_family(identity, expected):
    if not isinstance(expected, str) or not re.fullmatch(r'[A-Za-z0-9.-]{3,50}_[0-9a-hjkmnp-tv-z]{13}', expected):
        raise ValueError('Exact Partner Center package family name is required')
    actual = native_package_family(identity) if os.name == 'nt' else derived_package_family(identity)
    if actual.casefold() != expected.casefold():
        raise ValueError('Package Name/Publisher do not match the expected package family')
    return actual


def package_version(version, revision=0, explicit=None, previous=None):
    if not re.fullmatch(r'[0-9]+\.[0-9]+\.[0-9]+', version):
        raise ValueError('MSIX requires a stable three-part Cargo version; select an explicit release version')
    values = [int(v) for v in version.split('.')] + [revision]
    # Store requires a nonzero major; preserve monotonicity across Cargo 0.x.
    values[0] += 1
    if any(v < 0 or v > 65535 for v in values) or not any(values):
        raise ValueError('MSIX version components must be 0..65535 and not all zero')
    # Microsoft Store reserves the fourth part for Store processing.
    if revision != 0:
        raise ValueError('MSIX fourth version component is reserved; it must be zero')
    if explicit is not None:
        if not re.fullmatch(r'[0-9]+\.[0-9]+\.[0-9]+\.0', explicit):
            raise ValueError('Explicit MSIX version must be four numeric parts with final zero')
        values = [int(v) for v in explicit.split('.')]
    if values[0] < 1 or any(v > 65535 for v in values):
        raise ValueError('Store MSIX major must be positive and all components at most 65535')
    result = '.'.join(map(str, values))
    if previous is not None:
        prior = package_version(version, explicit=previous)
        if tuple(values) <= tuple(map(int, prior.split('.'))):
            raise ValueError('MSIX update version must be greater than the previous published version')
    return result


def manifest_bytes(template, identity, version, extra_types=(), msix_version=None):
    extra = sorted(set(extra_types))
    if not set(extra) <= OPTIONAL_TYPES:
        raise ValueError('Unsupported optional file association')
    values = {
        'IDENTITY_NAME': identity['name'], 'PUBLISHER': identity['publisher'],
        'PUBLISHER_DISPLAY_NAME': identity['publisher_display_name'],
        'VERSION': package_version(version, explicit=msix_version),
    }
    text = template.decode('utf-8')
    for key, value in values.items():
        text = text.replace('{{' + key + '}}', escape(value, {'"': '&quot;', "'": '&apos;'}))
    text = text.replace('{{FILE_TYPES}}', ''.join(f'<uap:FileType>{ext}</uap:FileType>' for ext in PROJECT_TYPES + extra))
    if '{{' in text:
        raise ValueError('Unresolved manifest placeholder')
    data = text.encode('utf-8')
    validate_manifest(data, identity, version, extra, msix_version)
    return data


def validate_manifest(data, identity, version, extra_types=(), msix_version=None):
    root = ET.fromstring(data)
    entry = root.find('f:Identity', NS)
    if entry is None or entry.attrib != {'Name': identity['name'], 'Publisher': identity['publisher'], 'Version': package_version(version, explicit=msix_version), 'ProcessorArchitecture': 'x64'}:
        raise ValueError('Manifest identity/version mismatch')
    dependencies = root.findall('f:Dependencies/f:PackageDependency', NS)
    if len(dependencies) != 1 or dependencies[0].attrib != {
        'Name': 'Microsoft.VCLibs.140.00.UWPDesktop', 'MinVersion': '14.0.30704.0',
        'Publisher': 'CN=Microsoft Corporation, O=Microsoft Corporation, L=Redmond, S=Washington, C=US',
    }:
        raise ValueError('Missing approved desktop Visual C++ runtime framework dependency')
    applications = root.findall('f:Applications/f:Application', NS)
    if len(applications) != 1 or applications[0].get('Executable') != 'peerbrush.exe':
        raise ValueError('Expected one native PeerBrush application')
    app = applications[0]
    if app.get('{'+NS['uap10']+'}RuntimeBehavior') != 'packagedClassicApp' or app.get('{'+NS['uap10']+'}TrustLevel') != 'mediumIL':
        raise ValueError('Expected normal-user full-trust desktop runtime')
    aliases = app.findall('f:Extensions/uap5:Extension/uap5:AppExecutionAlias/uap5:ExecutionAlias', NS)
    if len(aliases) != 1 or aliases[0].get('Alias') != 'peerbrush-mcp.exe':
        raise ValueError('Missing stable MCP execution alias')
    fta = app.find('f:Extensions/uap:Extension/uap3:FileTypeAssociation', NS)
    if fta is None or fta.get('Parameters') != '--open "%1"' or fta.get('MultiSelectModel') != 'Document':
        raise ValueError('File activation must quote the path and open each document')
    types = [n.text for n in fta.findall('uap:SupportedFileTypes/uap:FileType', NS)]
    if types != PROJECT_TYPES + sorted(set(extra_types)):
        raise ValueError('Unexpected file associations')
    caps = {n.get('Name') for n in root.findall('f:Capabilities/rescap:Capability', NS)}
    if caps != {'runFullTrust'}:
        raise ValueError('Unexpected capabilities')
    exclusions = [n.text for n in root.findall('f:Properties/virtualization:FileSystemWriteVirtualization/virtualization:ExcludedDirectories/virtualization:ExcludedDirectory', NS)]
    if exclusions or b'FileSystemWriteVirtualization' in data or b'RegistryWriteVirtualization' in data:
        raise ValueError('Package virtualization must remain enabled without exclusions')


def verified_portable(root, archive_path):
    """Validate exact source, allowlisted payload, PE architecture and all hashes."""
    if portable.git(root, 'status', '--porcelain', '--untracked-files=no').strip():
        raise ValueError('Commit tracked changes before creating an MSIX')
    commit = portable.git(root, 'rev-parse', 'HEAD').decode().strip()
    sources = portable.source_files(root, commit)
    expected_source = {name: data for name, data, _ in sources}
    version = tomllib.loads(expected_source['Cargo.toml'].decode())['package']['version']
    prefix = f'PeerBrush-{version}-Windows-x64/'
    with zipfile.ZipFile(archive_path) as archive:
        names = archive.namelist()
        if len(names) != len(set(n.casefold() for n in names)) or sum(i.file_size for i in archive.infolist()) > 512*1024*1024:
            raise ValueError('Duplicate portable entries or excessive expanded size')
        if archive.testzip() is not None:
            raise ValueError('Portable archive CRC failure')
        files = {}
        for entry in archive.infolist():
            portable.relative_path(entry.filename)
            if not entry.filename.startswith(prefix) or entry.external_attr >> 16 & 0o170000 not in (0, 0o100000):
                raise ValueError('Invalid portable archive path or non-regular entry')
            files[entry.filename[len(prefix):]] = archive.read(entry)
    release = json.loads(files['release.json'])
    expected = {'commit': commit, 'version': version, 'platform': 'Windows', 'architecture': 'x64', 'executable': 'peerbrush.exe', 'source': f'PeerBrush-{version}-source.zip', 'license': 'GPL-3.0-only', 'native_publisher_signing': 'not-configured'}
    if any(release.get(k) != v for k, v in expected.items()) or release.get('binary_source_commit', commit) != commit:
        raise ValueError('Windows executable/source must come from this exact commit')
    if 'macos_signing' in release:
        raise ValueError('Unexpected native signing metadata in Windows portable package')
    notices = release.get('notice_files')
    if not isinstance(notices, dict) or not notices:
        raise ValueError('Missing notice inventory')
    selected = {n: d for n, d, _ in portable.portable_files(sources)}
    expected_names = set(selected) | set(notices) | {'peerbrush.exe', 'release.json', 'THIRD_PARTY_NOTICES.md', release['source'], 'Start PeerBrush.cmd'}
    if set(files) != expected_names or any(files[n] != data for n, data in selected.items()) or files['Start PeerBrush.cmd'] != expected_source['scripts/start-windows.cmd']:
        raise ValueError('Unexpected payload or source mismatch in portable package')
    for name, digest in notices.items():
        if portable.relative_path(name).parts[0] != 'licenses' or sha(files[name]) != digest:
            raise ValueError('Notice checksum mismatch')
    # These required notices are reproducible from the committed source itself.
    # Other downloaded-crate notices retain the build's checksum inventory; use
    # the explicitly selected input archive hash as the upstream trust boundary.
    required_notices = {'licenses/ubuntu-sans/LICENCE.txt': expected_source['assets/fonts/LICENCE.txt']}
    policy = portable.policy_from_sources(sources)
    for directory in policy['vendored']:
        meta = tomllib.loads(expected_source[directory + '/Cargo.toml'].decode())['package']
        key = f"{meta['name']}-{meta['version']}"
        for name, data in expected_source.items():
            path = portable.relative_path(name)
            if str(path.parent) == directory and path.name.casefold() in portable.NOTICE_NAMES:
                required_notices[f'licenses/{key}/{path.name}'] = data
    if any(name not in notices or files.get(name) != data for name, data in required_notices.items()):
        raise ValueError('Required source-derived notice missing or changed')
    summary = files['THIRD_PARTY_NOTICES.md'].decode('utf-8')
    normalized_summary = summary.replace('\r\n', '\n')
    if '\r' in normalized_summary or not normalized_summary.startswith('# Third-party notices\n') or 'Cargo.lock' not in normalized_summary:
        raise ValueError('Missing third-party notice summary')
    if sha(files['peerbrush.exe']) != release['executable_sha256'] or sha(files[release['source']]) != release['source_sha256']:
        raise ValueError('Executable/source checksum mismatch')
    if portable.architecture_from_stream(io.BytesIO(files['peerbrush.exe']), 'Windows') != 'x64':
        raise ValueError('Expected Windows x64 PE')
    portable.validate_binary(files['peerbrush.exe'])
    with zipfile.ZipFile(io.BytesIO(files[release['source']])) as source:
        if sum(i.file_size for i in source.infolist()) > 512*1024*1024:
            raise ValueError('Corresponding source exceeds inspection budget')
        if source.testzip() is not None or len(source.namelist()) != len(set(source.namelist())) or set(source.namelist()) != set(expected_source) or any(source.read(n) != d for n,d in expected_source.items()):
            raise ValueError('Corresponding source differs from selected commit')
    return files, expected_source, release


def validate_casefold_paths(paths):
    """Windows is normally case-insensitive, including every parent directory."""
    files = list(paths)
    if len(files) != len({name.casefold() for name in files}):
        raise ValueError('Case-insensitive payload filename collision')
    seen = {}
    file_names = {name.casefold() for name in files}
    for name in files:
        path = portable.relative_path(name)
        for candidate in [path, *path.parents]:
            if str(candidate) == '.':
                continue
            spelling = candidate.as_posix()
            folded = spelling.casefold()
            if folded in seen and seen[folded] != spelling:
                raise ValueError('Case-insensitive payload directory collision')
            if candidate != path and folded in file_names:
                raise ValueError('Payload file collides with a directory')
            seen[folded] = spelling


def stage_payload(root, archive, destination, identity, extra_types=(), msix_version=None):
    files, sources, release = verified_portable(root, archive)
    validate_casefold_paths([*files, 'AppxManifest.xml', *['MsixAssets/'+name for name in ASSETS]])
    if destination.exists():
        raise ValueError('MSIX staging destination must be new')
    destination.mkdir(parents=True)
    # Keep the complete matching GPL source and notices in the installed package.
    for name, data in files.items():
        target = destination / portable.relative_path(name)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    manifest = manifest_bytes(sources['packaging/msix/AppxManifest.xml.in'], identity, release['version'], extra_types, msix_version)
    (destination/'AppxManifest.xml').write_bytes(manifest)
    (destination/'MsixAssets').mkdir()
    for name, size in ASSETS.items():
        data = sources['packaging/msix/Assets/'+name]
        if data[:8] != b'\x89PNG\r\n\x1a\n' or struct.unpack('>II', data[16:24]) != (size,size):
            raise ValueError('Missing or incorrectly sized MSIX image')
        (destination/'MsixAssets'/name).write_bytes(data)
    return release


def find_makeappx(explicit=None):
    if explicit:
        path = pathlib.Path(explicit).resolve(strict=True)
    else:
        found = shutil.which('MakeAppx.exe')
        base = pathlib.Path(os.environ.get('ProgramFiles(x86)', r'C:\Program Files (x86)')) / 'Windows Kits/10/bin'
        candidates = sorted(base.glob('*/x64/MakeAppx.exe'), reverse=True)
        path = pathlib.Path(found) if found else (candidates[0] if candidates else None)
    if path is None or not path.is_file():
        raise ValueError('Windows SDK MakeAppx.exe is required; no MSIX was built')
    return path


def opc_name(name):
    from urllib.parse import quote
    if name == '[Content_Types].xml':
        return name
    portable.relative_path(name)
    return quote(name, safe='/~.-_')


def verify_packed(package_path, staged):
    expected = {p.relative_to(staged).as_posix(): p.read_bytes() for p in staged.rglob('*') if p.is_file()}
    encoded = {opc_name(name): data for name, data in expected.items()}
    with zipfile.ZipFile(package_path) as package:
        names = package.namelist()
        # MakeAppx's footprint files are generated by the official SDK.
        footprint = {'[Content_Types].xml', 'AppxBlockMap.xml'}
        if (len(encoded) != len(expected) or len(names) != len(set(n.casefold() for n in names))
                or set(names) != set(encoded) | footprint
                or sum(i.file_size for i in package.infolist()) > 512*1024*1024):
            raise ValueError('Unexpected/missing MSIX entries or unexpected signature')
        if package.testzip() is not None or any(package.read(n) != data for n,data in encoded.items()):
            raise ValueError('MSIX payload differs from validated staging')
        blocks = ET.fromstring(package.read('AppxBlockMap.xml'))
        ns = {'b': 'http://schemas.microsoft.com/appx/2010/blockmap'}
        if blocks.get('HashMethod') != 'http://www.w3.org/2001/04/xmlenc#sha256':
            raise ValueError('Unexpected block-map hash algorithm')
        block_files = blocks.findall('b:File',ns)
        if len(block_files) != len(expected) or {n.get('Name').replace('\\','/') for n in block_files} != set(expected):
            raise ValueError('MSIX block map does not cover the complete payload')
        import base64
        for node in block_files:
            data=expected[node.get('Name').replace('\\','/')]
            hashes=[n.get('Hash') for n in node.findall('b:Block',ns)]
            actual=[base64.b64encode(hashlib.sha256(data[i:i+65536]).digest()).decode() for i in range(0,len(data),65536)]
            if int(node.get('Size')) != len(data) or hashes != actual:
                raise ValueError('MSIX block hash mismatch')


def build(root, archive, output, identity, development=False, makeappx=None, extra_types=(), msix_version=None, previous_version=None, expected_sha256=None, expected_package_family=None):
    identity_values(identity, development)
    if not development and not re.fullmatch(r'[0-9a-f]{64}', expected_sha256 or ''):
        raise ValueError('Store candidate requires the explicitly selected portable SHA-256')
    if expected_sha256 is not None and portable.digest(archive) != expected_sha256:
        raise ValueError('Portable archive SHA-256 differs from the selected input')
    family = validate_package_family(identity, expected_package_family) if not development or expected_package_family else None
    packager = find_makeappx(makeappx)
    output.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='.peerbrush-msix-', dir=output) as temporary:
        temporary = pathlib.Path(temporary)
        stage = temporary/'payload'
        release = stage_payload(root, archive, stage, identity, extra_types, msix_version)
        final_version = package_version(release['version'], explicit=msix_version, previous=previous_version)
        label = '-local-test' if development else ''
        name = f"PeerBrush-{final_version}-Windows-x64{label}.msix"
        result = temporary/name
        subprocess.run([str(packager), 'pack', '/d', str(stage.resolve()), '/p', str(result.resolve()), '/o'], check=True)
        verify_packed(result,stage)
        report = {'schema':1,'package':name,'sha256':portable.digest(result),'commit':release['commit'],'app_version':release['version'],'version':final_version,'identity':identity,'package_family_name':family,'development_identity':development,'signed':False,'portable_sha256':portable.digest(archive),'installed_tested':False,'file_types':PROJECT_TYPES+sorted(set(extra_types)),'validation':'MakeAppx schema/semantic validation and byte/block-hash verification'}
        report_path = temporary/(name+'.json')
        report_path.write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
        sums = temporary/(name+'.sha256')
        sums.write_text(f"{report['sha256']}  {name}\n",encoding='utf-8')
        for path in [result,report_path,sums]:
            target=output/path.name
            if target.exists() or target.is_symlink():
                raise ValueError('Refusing to overwrite an existing MSIX result; choose a new output directory')
        for path in [result,report_path,sums]:
            os.replace(path,output/path.name)
        return report


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--portable',required=True,type=pathlib.Path)
    group=parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--identity',type=pathlib.Path,help='Exact Partner Center identity JSON; no placeholders')
    group.add_argument('--development-identity',action='store_true',help='Explicit local test identity; never publish this to the Store')
    parser.add_argument('--output',type=pathlib.Path,default=pathlib.Path('dist/msix'))
    parser.add_argument('--makeappx',type=pathlib.Path)
    parser.add_argument('--expected-package-family',help='Required for Store: exact Partner Center package family name')
    parser.add_argument('--portable-sha256',help='Required for Store: independently selected input archive SHA-256')
    parser.add_argument('--package-version',help='Override mapped Store version, e.g. 1.2.0.0')
    parser.add_argument('--previous-version',help='Previous published MSIX version; enforce a strictly newer update')
    parser.add_argument('--associate',action='append',default=[],choices=sorted(OPTIONAL_TYPES))
    args=parser.parse_args()
    try:
        identity = DEVELOPMENT_IDENTITY.copy() if args.development_identity else json.loads(args.identity.read_text(encoding='utf-8'))
        root=pathlib.Path(__file__).resolve().parents[1]
        result=build(root,args.portable,args.output,identity,args.development_identity,args.makeappx,args.associate,args.package_version,args.previous_version,args.portable_sha256,args.expected_package_family)
        print(json.dumps(result,indent=2))
    except (ValueError,KeyError,OSError,subprocess.SubprocessError,zipfile.BadZipFile,ET.ParseError) as error:
        parser.exit(1,'MSIX packaging failed: '+str(error)+'\n')


if __name__=='__main__':
    main()
